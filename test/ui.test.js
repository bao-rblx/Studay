// Static checks on the frontend: the page and the scripts must agree with each other.
// There is no browser in CI, so these cheap invariants catch the classic breakage —
// a missing file, a renamed element id, a typo that only shows up at runtime.
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const PUBLIC = path.join(__dirname, '..', 'public');
const html = fs.readFileSync(path.join(PUBLIC, 'index.html'), 'utf8');
const SCRIPTS = ['app.js', 'feature-files.js', 'feature-quiz.js', 'feature-search.js'];
const FEATURES = ['feature-files.js', 'feature-quiz.js', 'feature-search.js'];

test('every file the page loads exists in public/', () => {
  const refs = [...html.matchAll(/(?:src|href)="([^":]+)"/g)].map((m) => m[1]);
  assert.ok(refs.length >= 8, 'expected the stylesheets and scripts to be linked');
  for (const ref of refs) assert.ok(fs.existsSync(path.join(PUBLIC, ref)), `${ref} is linked but missing`);
});

test('app.js is loaded before the feature files', () => {
  const order = [...html.matchAll(/<script src="([^"]+)"/g)].map((m) => m[1]);
  assert.equal(order[0], 'app.js');
  assert.deepEqual(order.slice(1).sort(), [...FEATURES].sort());
});

test('every element id a script looks up exists in the page', () => {
  // Modal bodies are generated by the scripts themselves, so their ids count too.
  const ids = new Set([...html.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]));
  for (const file of SCRIPTS) {
    const src = fs.readFileSync(path.join(PUBLIC, file), 'utf8');
    for (const match of src.matchAll(/\bid="([A-Za-z][\w-]*)"/g)) ids.add(match[1]);
  }
  const missing = [];
  for (const file of SCRIPTS) {
    const src = fs.readFileSync(path.join(PUBLIC, file), 'utf8');
    const patterns = [/\$\(\s*'([A-Za-z][\w-]*)'\s*\)/g, /getElementById\(\s*'([A-Za-z][\w-]*)'\s*\)/g];
    for (const pattern of patterns) {
      for (const match of src.matchAll(pattern)) {
        if (!ids.has(match[1])) missing.push(`${file} -> #${match[1]}`);
      }
    }
  }
  assert.deepEqual(missing, [], 'scripts look up ids the page does not define');
});

test('no element id is declared twice', () => {
  const all = [...html.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]);
  const dupes = [...new Set(all.filter((id, i) => all.indexOf(id) !== i))];
  assert.deepEqual(dupes, []);
});

test('every frontend script parses as a classic script', () => {
  for (const file of SCRIPTS) {
    const src = fs.readFileSync(path.join(PUBLIC, file), 'utf8');
    assert.doesNotThrow(() => new vm.Script(src, { filename: file }), `${file} has a syntax error`);
  }
});

test('each feature file registers itself on the Studay namespace', () => {
  for (const file of FEATURES) {
    const src = fs.readFileSync(path.join(PUBLIC, file), 'utf8');
    assert.match(src, /window\.Studay\.register\(/, `${file} must call window.Studay.register()`);
  }
});

test('the sign-in card is the only way into the app', () => {
  // The auth screen ships visible in the markup only through .hidden, which app.js removes
  // when a session exists; the app shell is hidden while signed out.
  assert.match(html, /id="auth-screen"[^>]*class="auth-screen hidden"/);
  assert.match(fs.readFileSync(path.join(PUBLIC, 'styles.css'), 'utf8'), /body\.signed-out \.app \{ display: none; \}/);
});
