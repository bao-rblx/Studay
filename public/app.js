function toast(msg) { const t = $('toast'); t.textContent = msg; t.classList.add('show'); setTimeout(() => t.classList.remove('show'), 2600); }
function addXP(n) { const xp = store.get('sd_xp', 0) + n; store.set('sd_xp', xp); $('xp-val').textContent = xp; }
function touchStreak() {
  const today = new Date().toDateString();
  const last = store.get('sd_last', '');
  let streak = store.get('sd_streak', 0);
  if (last !== today) {
    const y = new Date(Date.now() - 864e5).toDateString();
    streak = (last === y) ? streak + 1 : 1;
    store.set('sd_streak', streak); store.set('sd_last', today);
  }
  $('streak-val').textContent = store.get('sd_streak', 0);
}

// Disable a button while an async action runs, so double clicks do not send twice.
async function busy(btn, label, fn) {
  const old = btn ? btn.textContent : '';
  if (btn) { btn.disabled = true; btn.textContent = label; }
  try { return await fn(); } finally { if (btn) { btn.disabled = false; btn.textContent = old; } }
}

