function renderUpcoming() {
  const today = ymd(new Date());
  const now = new Date(`${today}T00:00:00`);
  const list = state.events.filter((e) => !e.done && e.event_date >= today).slice(0, 8);
  $('upcoming').innerHTML = list.map((e) => {
    const days = Math.round((new Date(`${e.event_date}T00:00:00`) - now) / 864e5);
    const when = days === 0 ? 'today' : days === 1 ? 'tomorrow' : `in ${days} days`;
    return `<div class="up-item ${days <= 3 ? 'urgent' : ''}" style="--c:${esc(colorOf(e))}">
      <span>${KIND_ICON[e.kind] || ''} <strong>${esc(e.title)}</strong> <small>${esc(e.event_date)} · ${when}</small></span>
      <span class="row-actions"><button class="ghost" onclick="openEvent(${e.id})">Edit</button><button class="ok" onclick="markDone(${e.id})">Done</button></span></div>`;
  }).join('') || '<p class="hint">Nothing coming up. Type a quick note above to add something.</p>';
}
async function markDone(id) { await send(`/api/events/${id}`, { done: true }, 'PUT'); addXP(10); toast('Nice work! +10 XP'); refresh(); }

function eventForm(e, editing) {
  return `<label>Title<input id="f-title" value="${esc(e.title)}" required></label>
    <div class="row2"><label>Date<input type="date" id="f-date" value="${esc(e.event_date)}" required></label>
    <label>Time<input type="time" id="f-time" value="${esc(e.start_time || '')}"></label></div>
    <div class="row2"><label>Type<select id="f-kind">${KINDS.map((k) => `<option value="${k}" ${k === e.kind ? 'selected' : ''}>${KIND_ICON[k]} ${k}</option>`).join('')}</select></label>
    <label>Subject<select id="f-subject" ${editing ? 'disabled' : ''}><option value="">None</option>${state.subjects.map((s) => `<option value="${s.id}" ${s.id === e.subject_id ? 'selected' : ''}>${esc(s.name)}</option>`).join('')}</select></label></div>
    <label>Details<textarea id="f-details">${esc(e.details || '')}</textarea></label>`;
}
function readEventForm() {
  const body = {
    title: $('f-title').value.trim(), event_date: $('f-date').value, start_time: $('f-time').value || null,
    kind: $('f-kind').value, details: $('f-details').value.trim() || null,
  };
  if (!$('f-subject').disabled) body.subject_id = $('f-subject').value ? Number($('f-subject').value) : null;
  if (!body.title || !body.event_date) { toast('Title and date are required'); return null; }
  return body;
}
// New event, optionally pre-filled by the AI (the user always confirms first).
function openEventEditor(e, { title = 'New event', intro = '' } = {}) {
  openModal(title, intro + eventForm(e, false), async () => {
    const body = readEventForm();
    if (!body) return false;
    await send('/api/events', body);
    addXP(5); toast('Added to your calendar +5 XP'); refresh();
  }, 'Add to calendar');
}
function newEvent(date) { openEventEditor({ title: '', event_date: date, kind: 'deadline' }); }
function openEvent(id) {
  const e = state.events.find((x) => x.id === id);
  if (!e) return;
  openModal('Edit event', eventForm(e, true) + `<button type="button" class="danger" onclick="delEvent(${id})">Delete event</button>`, async () => {
    const body = readEventForm();
    if (!body) return false;
    await send(`/api/events/${id}`, body, 'PUT');
    refresh();
  });
}
async function delEvent(id) { if (!confirm('Delete this event?')) return; await api(`/api/events/${id}`, { method: 'DELETE' }); closeModal(); refresh(); }

