// The sign-in card talks to fetch directly: a 401 here is a normal answer, not a failure.
async function authRequest(path, payload) {
  try {
    const res = await fetch(path, { method: 'POST', headers: JSON_HEADERS, body: JSON.stringify(payload) });
    const body = await res.json().catch(() => ({}));
    return { ok: res.ok, body };
  } catch {
    return { ok: false, body: { error: 'cannot reach the server' } };
  }
}
async function bootAuth() {
  let user = null;
  try { user = (await api('/api/auth/me', { allow401: true })).user || null; } catch { user = null; }
  if (!user) return showAuth();
  return signedIn(user);
}
function signedIn(user) {
  state.user = user;
  // Switch progress storage to this account's namespace before anything reads it.
  store.ns = user && user.id ? `sd.u${user.id}.` : '';
  renderUserChip();
  hideAuth();
  touchStreak();
  $('xp-val').textContent = store.get('sd_xp', 0);
  features.forEach((f) => { try { f.init?.(); } catch (err) { console.error(`[feature:${f.name}] init failed`, err); } });
  return refresh().catch(() => {});
}
async function logout() {
  try { await api('/api/auth/logout', { method: 'POST' }); } catch { /* the cookie is gone either way */ }
  state.user = null;
  state.subjects = []; state.notes = []; state.materials = []; state.events = [];
  store.ns = '';
  renderUserChip();
  showAuth();
}
$('auth-switch').addEventListener('click', () => setAuthMode(authMode === 'login' ? 'register' : 'login'));
$('auth-form').addEventListener('submit', async (e) => {
  e.preventDefault();
  const email = $('auth-email').value.trim();
  const password = $('auth-password').value;
  const name = $('auth-name').value.trim();
  if (!email) return authError('Enter your email address.');
  if (password.length < 8) return authError('Passwords need at least 8 characters.');
  const btn = $('auth-submit');
  btn.disabled = true;
  const path = authMode === 'login' ? '/api/auth/login' : '/api/auth/register';
  const { ok, body } = await authRequest(path, { email, password, display_name: name || undefined });
  btn.disabled = false;
  if (!ok) return authError(body.error || 'That did not work. Try again.');
  $('auth-password').value = '';
  authError('');
  toast(authMode === 'login' ? 'Welcome back!' : 'Account created');
  signedIn(body.user);
});

