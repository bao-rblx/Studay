// Every call goes through here so failures show a message instead of breaking the page.
async function api(url, opts = {}) {
  let res;
  try {
    res = await fetch(url, opts);
  } catch {
    showBanner('Cannot reach the server. Check your connection and try again.');
    throw new Error('network');
  }
  const body = await res.json().catch(() => ({}));
  // A missing or expired session sends the user back to the sign-in card.
  if (res.status === 401) {
    if (opts.allow401) return body;
    showAuth();
    throw new Error('signed out');
  }
  if (res.status === 503) {
    showBanner('The database is waking up (free tier). Retrying in 10 seconds...');
    setTimeout(() => refresh().catch(() => {}), 10000);
    throw new Error('db_down');
  }
  if (!res.ok) {
    toast(body.error || `Request failed (${res.status})`);
    throw new Error(body.error || String(res.status));
  }
  hideBanner();
  return body;
}
const send = (url, body, method = 'POST') => api(url, { method, headers: JSON_HEADERS, body: JSON.stringify(body) });
function showBanner(msg) { const b = $('status-banner'); b.textContent = msg; b.classList.remove('hidden'); }
function hideBanner() { $('status-banner').classList.add('hidden'); }

// ---------- small helpers ----------
const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
// Progress (XP, streak, quiz history) belongs to the account, not to the browser, so the
// keys get a per-user prefix once somebody is signed in. The theme is a device
// preference and stays shared.
const store = {
  ns: '',
  get: (k, d) => { try { const v = JSON.parse(localStorage.getItem(store.ns + k)); return v ?? d; } catch { return d; } },
  set: (k, v) => localStorage.setItem(store.ns + k, JSON.stringify(v)),
};
const themePref = () => localStorage.getItem('sd_theme') || 'light';
const pad = (n) => String(n).padStart(2, '0');
const ymd = (d) => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
const DAY_SHORT = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
const KINDS = ['deadline', 'exam', 'presentation', 'class', 'other'];
