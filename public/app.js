function renderCalendar() {
  $('cal-title').textContent = calMonth.toLocaleDateString(undefined, { month: 'long', year: 'numeric' });
  $('cal-weekdays').innerHTML = DAY_SHORT.map((d) => `<div class="wd">${d}</div>`).join('');
  const start = new Date(calMonth); start.setDate(1 - calMonth.getDay());
  const today = ymd(new Date());
  const showClasses = $('cal-show-classes').checked;
  let html = '';
  for (let i = 0; i < 42; i++) {
    const d = new Date(start); d.setDate(start.getDate() + i);
    const key = ymd(d);
    const classes = showClasses
      ? subjects.flatMap((s) => (s.schedule || []).filter((c) => c.day === d.getDay()).map((c) => ({ s, c })))
        .sort((a, b) => String(a.c.start).localeCompare(String(b.c.start)))
      : [];
    const chips = [
      ...events.filter((e) => e.event_date === key).map((e) =>
        `<button class="chip ev ${e.done ? 'done' : ''}" style="--c:${esc(colorOf(e))}" data-event="${e.id}" title="${esc(e.title)}">${KIND_ICON[e.kind] || ''} ${esc(e.start_time || '')} ${esc(e.title)}</button>`),
      ...classes.map(({ s, c }) => `<div class="chip class" style="--c:${esc(s.color)}">${esc(c.start || '')} ${esc(s.name)}</div>`),
    ];
    const label = d.toLocaleDateString(undefined, { weekday: 'long', day: 'numeric', month: 'long' });
    html += `<div class="day ${d.getMonth() !== calMonth.getMonth() ? 'out' : ''} ${key === today ? 'today' : ''}" data-date="${key}" role="button" tabindex="0" aria-label="${esc(label)}, add event">
      <span class="num">${d.getDate()}</span>${chips.slice(0, 4).join('')}${chips.length > 4 ? `<small class="more">+${chips.length - 4} more</small>` : ''}</div>`;
  }
  $('cal-days').innerHTML = html;
  renderUpcoming();
}
