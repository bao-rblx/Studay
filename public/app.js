function renderUpcoming() {
  const today = ymd(new Date());
  const now = new Date(`${today}T00:00:00`);
  const list = events.filter((e) => !e.done && e.event_date >= today).slice(0, 8);
  $('upcoming').innerHTML = list.map((e) => {
    const days = Math.round((new Date(`${e.event_date}T00:00:00`) - now) / 864e5);
    const when = days === 0 ? 'today' : days === 1 ? 'tomorrow' : `in ${days} days`;
    return `<div class="up-item ${days <= 3 ? 'urgent' : ''}" style="--c:${esc(colorOf(e))}">
      <span>${KIND_ICON[e.kind] || ''} <strong>${esc(e.title)}</strong> <small>${esc(e.event_date)} · ${when}</small></span>
      <span class="row-actions"><button class="ghost" onclick="openEvent(${e.id})">Edit</button><button class="ok" onclick="markDone(${e.id})">Done</button></span></div>`;
  }).join('') || '<p class="hint">Nothing coming up. Type a quick note above to add something.</p>';
}
