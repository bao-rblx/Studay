// ---------- data loading ----------
async function refresh() {
  if (!state.user) return;
  [state.subjects, state.notes, state.materials, state.events] = await Promise.all([
    api('/api/subjects'), api('/api/notes'), api('/api/materials'), api('/api/events'),
  ]);
  renderAll();
}
