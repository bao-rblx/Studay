function readAsBase64(file) {
  return new Promise((resolve, reject) => {
    const r = new FileReader();
    r.onload = () => resolve(String(r.result).split(',')[1] || '');
    r.onerror = () => reject(r.error);
    r.readAsDataURL(file);
  });
}
const isTextFile = (f) => f.type.startsWith('text/') || /\.(txt|md)$/i.test(f.name);
// Let a .drop panel accept dragged files as well as the file picker.
function wireDrop(panelId, inputId, handler) {
  const panel = $(panelId), input = $(inputId);
  input.addEventListener('change', () => { if (input.files[0]) handler(input.files[0]); input.value = ''; });
  panel.addEventListener('dragover', (e) => { e.preventDefault(); panel.classList.add('over'); });
  panel.addEventListener('dragleave', () => panel.classList.remove('over'));
  panel.addEventListener('drop', (e) => {
    e.preventDefault(); panel.classList.remove('over');
    if (e.dataTransfer.files[0]) handler(e.dataTransfer.files[0]);
  });
}

