function summaryHtml(out) {
  const s = out.summary;
  return aiNotice(out) + aiSource(out) + (s
    ? `<div class="ai-block"><p>${esc(s.summary)}</p><ul>${(s.key_points || []).map((k) => `<li>${esc(k)}</li>`).join('')}</ul></div>`
    : '<p class="hint">No summary available.</p>');
}
function renderNotes() {
  const f = $('notes-filter-subject').value;
  const q = $('notes-search').value.toLowerCase();
  const list = state.notes.filter((n) => (!f || String(n.subject_id) === f) && (!q || (n.title + ' ' + n.content).toLowerCase().includes(q)));
  $('note-list').innerHTML = list.map((n) => `<div class="note"><strong>${esc(n.title)}</strong>
    <small>${esc(subjectOf(n.subject_id)?.name || '')}</small>
    <p>${esc(n.content.slice(0, 220))}${n.content.length > 220 ? '...' : ''}</p>
    <div class="row-actions"><button onclick="summariseNote(${n.id})">✨ Summarise</button>
      <button class="ghost" onclick="editNote(${n.id})">Edit</button>
      <button class="danger" onclick="delNote(${n.id})">Delete</button></div>
    <div id="note-ai-${n.id}"></div></div>`).join('') || '<p class="hint">No notes match.</p>';
}
async function summariseNote(id) {
  const box = $(`note-ai-${id}`);
  box.innerHTML = '<div class="ai-loading">Reading...</div>';
  try { box.innerHTML = summaryHtml(await send('/api/ai/generate', { note_id: id, mode: 'summary' })); } catch { box.innerHTML = ''; }
}
function editNote(id) {
  const n = state.notes.find((x) => x.id === id);
  if (!n) return;
  openModal('Edit note', `<label>Title<input id="f-ntitle" value="${esc(n.title)}"></label>
    <label>Content<textarea id="f-ncontent" rows="8">${esc(n.content)}</textarea></label>`, async () => {
    await send(`/api/notes/${id}`, { title: $('f-ntitle').value, content: $('f-ncontent').value }, 'PUT'); refresh();
  });
}
async function delNote(id) { if (!confirm('Delete this note?')) return; await api(`/api/notes/${id}`, { method: 'DELETE' }); refresh(); }
